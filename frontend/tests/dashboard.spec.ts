import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const env=Object.fromEntries(readFileSync('../.env','utf8').split(/\r?\n/).filter(l=>l.includes('=')).map(l=>{const i=l.indexOf('=');return [l.slice(0,i).trim(),l.slice(i+1).trim()]}))

test('catalog review, simulator, live handover and responsive dashboard',async({page,browser})=>{
  test.setTimeout(90_000)
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Usuario',{exact:true}).fill(env.ADMIN_USERNAME||'admin')
  await page.getByLabel('Contraseña',{exact:true}).fill(env.ADMIN_PASSWORD)
  await page.getByRole('button',{name:'Iniciar sesión'}).click()
  await expect(page.getByText('En tiempo real',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Catálogo de cursos',exact:true}).click()
  await page.getByRole('textbox',{name:'Buscar cursos'}).fill('GitHub')
  await page.getByRole('button',{name:'Revisar ficha'}).click()
  await expect(page.getByRole('dialog')).toContainText('$40,00')
  await page.getByRole('button',{name:'Aprobar y publicar'}).click()
  await expect(page.getByText('Curso publicado para el asistente')).toBeVisible()
  await page.screenshot({path:'../tmp/final-catalog.png',fullPage:true})
  await page.getByRole('button',{name:'Simulador',exact:true}).click()
  await page.getByLabel('Nombre del visitante').fill('QA Visitante')
  await page.getByRole('textbox',{name:'Mensaje de prueba'}).fill('Me interesa GitHub')
  await page.getByRole('button',{name:'Enviar consulta'}).click()
  await expect(page.locator('.message.assistant')).toHaveCount(1,{timeout:65_000})
  await page.getByRole('textbox',{name:'Mensaje de prueba'}).fill('No me entiendes, estoy harto')
  await page.getByRole('button',{name:'Enviar consulta'}).click()
  await expect(page.locator('.message.assistant')).toHaveCount(2)
  await page.getByRole('button',{name:'Ver prospecto'}).click()
  await expect(page.getByRole('button',{name:'Reanudar IA'})).toBeVisible()
  await expect(page.locator('.lead-details .badge')).toContainText('Frustrado')
  await page.getByRole('textbox',{name:'Respuesta del asesor'}).fill('Soy tu asesor y revisaré tu consulta.')
  await page.getByRole('button',{name:'Enviar respuesta'}).click()
  await expect(page.locator('.message.advisor')).toContainText('Soy tu asesor')
  await page.getByRole('button',{name:'Reanudar IA'}).click()
  await expect(page.getByRole('button',{name:'Tomar control'})).toBeVisible()
  // A second browser tab changes server state. SSE must update this tab without reload.
  const auth=await page.evaluate(()=>sessionStorage.getItem('ctt_token'))
  const second=await browser.newContext()
  const response=await second.request.get('http://127.0.0.1:8000/api/leads',{headers:{Authorization:`Bearer ${auth}`}})
  expect(response.ok()).toBe(true)
  const simulatorId=await page.evaluate(()=>sessionStorage.getItem('ctt_simulator'))
  const lead=(await response.json()).find((l:{external_id:string;channel:string})=>l.external_id===simulatorId && l.channel==='simulator')
  expect(lead).toBeTruthy()
  const takeover=await second.request.patch(`http://127.0.0.1:8000/api/leads/${lead.id}`,{headers:{Authorization:`Bearer ${auth}`},data:{stage:'seguimiento',handoff:true,owner:'Equipo QA'}})
  expect(takeover.ok()).toBe(true)
  await expect(page.getByRole('button',{name:'Reanudar IA'})).toBeVisible()
  await second.close()
  await page.screenshot({path:'../tmp/qa-inbox.png',fullPage:true})
  await page.getByRole('button',{name:'Resumen',exact:true}).click()
  await page.screenshot({path:'../tmp/qa-dashboard.png',fullPage:true})
  await page.screenshot({path:'../tmp/final-dashboard.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'../tmp/qa-mobile.png',fullPage:true})
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)
  expect(overflow).toBe(false)
  expect(errors).toEqual([])
})
